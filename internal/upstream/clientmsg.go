// ClientMessage 按业务码查客户端解释。未收录 → ok=false（不编造文案）。
func ClientMessage(code int) (CodeMessage, bool) {
	m, ok := codeMessages[code]
	return m, ok
}

// ExplainBody 从上游错误 body（或 SSE error 帧 payload）里解出业务码并查解释。
// 返回 (码, 解释, 是否命中码表)；解不出码时返回 (0, 零值, false)。
func ExplainBody(body string) (int, CodeMessage, bool) {
	code, ok := ExtractCode(body)
	if !ok {
		return 0, CodeMessage{}, false
	}
	m, hit := codeMessages[code]
	return code, m, hit
}

// ExtractCode 从 body 里解上游业务码，容错三种真实形态：
//   - {"code":11133,"msg":...}（WorkBuddy 主信封）
//   - {"extError":{"code":"model_param_invalid"}}（附加上下文，非数字，跳过）
//   - {"error":{"code":6004,"message":...}}（OpenAI 形态 / SSE 帧）
//
// JSON 解析失败（纯文本 body / HTML 网关页）时退化为对 `"code":<数字>` 的
// 子串扫描——错误路径宁可多认出一个码，也不要因为格式不规范丢掉整个解释层。
func ExtractCode(body string) (int, bool) {
	if body == "" {
		return 0, false
	}
	var probe struct {
		Code     json.RawMessage `json:"code"`
		Msg      string          `json:"msg"`
		ExtError struct {
			Code json.RawMessage `json:"code"`
		} `json:"extError"`
		Error struct {
			Code json.RawMessage `json:"code"`
		} `json:"error"`
	}
	if json.Unmarshal([]byte(body), &probe) == nil {
		for _, raw := range []json.RawMessage{probe.Code, probe.ExtError.Code, probe.Error.Code} {
			if n, ok := rawCodeInt(raw); ok && n != 0 {
				return n, true
			}
		}
	}
	if n, ok := scanCode(body); ok {
		return n, true
	}
	// 上游常把原始 body 塞进 error.message 的**字符串**里：转义后 "code" 变成
	// \"code\"，裸扫描命中不了。解一次转义再扫——只用于**取码**，透传原文不动。
	if un := strings.ReplaceAll(body, `\"`, `"`); un != body {
		return scanCode(un)
	}
	return 0, false
}

// rawCodeInt 把 JSON 数字或数字字符串转成 int；其它（对象/布尔/非数字串）→ false。
func rawCodeInt(raw json.RawMessage) (int, bool) {
	s := strings.TrimSpace(string(raw))
	if s == "" || s == "null" {
		return 0, false
	}
	if s[0] == '"' {
		s = strings.Trim(s, "\"")
	}
	n, err := strconv.Atoi(s)
	if err != nil {
		return 0, false
	}
	return n, true
}

// scanCode 在非 JSON body 里扫 `"code":<数字>` / `\"code\": <数字>` 形态。
// 只认后面紧跟数字的形态：extError 的字符串码（model_param_invalid）天然跳过。
func scanCode(body string) (int, bool) {
	for i := 0; i < len(body); i++ {
		j := strings.Index(body[i:], `"code"`)
		if j < 0 {
			return 0, false
		}
		k := i + j + len(`"code"`)
		for k < len(body) && (body[k] == ' ' || body[k] == '\t') {
			k++
		}
		if k < len(body) && body[k] == ':' {
			k++
			for k < len(body) && (body[k] == ' ' || body[k] == '\t') {
				k++
			}
			if k < len(body) && body[k] == '"' {
				k++
			}
			start := k
			for k < len(body) && body[k] >= '0' && body[k] <= '9' {
				k++
			}
			if k > start {
				if n, err := strconv.Atoi(body[start:k]); err == nil && n != 0 {
					return n, true
				}
			}
		}
		i += j + len(`"code"`)
	}
	return 0, false
}
