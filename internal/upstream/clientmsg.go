// clientmsg.go 错误三层诊断的「客户端解释」层（第二层）。
//
// 三层口径（API 响应与面板诊断共用同一份事实）：
//  1. 本网关判断 —— error.gateway_hint（hint.go，英文，「你该怎么做」）；
//  2. 客户端解释 —— error.client_message（本文件，中文，「这是什么意思」）；
//  3. 上游实际证据 —— error.message（上游 body 原文，一字不改）+ error.upstream_code
//     （从 body 里解出的业务码，便于对账到上游文档/工单）。
//
// 为什么第二层要独立成表、而不是复述 message：上游 message 经常是英文短句或
// 裸码（"Invalid request parameters" / 6008），对使用者没有信息量；客户端文案
// 是产品团队写好的中文解释，直接命中理解成本。三层并列而不是互相替换——
// 原文透传原则（5755fe3）不动，解释只是并排的补充。
//
// 表来源：WorkBuddy 客户端 app.asar 的 zh-cn 文案表（116 条，客户端真实显示
// 文案）+ workbuddy2api 1.0.5 admin 错误码库（147 条，多 31 条并带 detail）。
// 按 code 合并：Message 取客户端原文（用户看到的那句），Detail 取上游官方说明。
